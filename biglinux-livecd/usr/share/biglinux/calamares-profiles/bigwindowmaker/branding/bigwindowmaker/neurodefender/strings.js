var tables = { en: en, pt: pt };

// "pt_BR" -> pt; anything unknown -> en
function forLocale(name) {
    var lang = String(name || "").split(/[_-]/)[0];
    return tables[lang] || en;
}

function fill(text, arg) {
    return String(text).replace("%1", arg);
}
